export async function pingServerStatus(host: string, port: number): Promise<ServerStatus> {
  try {
    const result = await minecraftAPI.pingServer(host, port)
    return {
      online: result.online ?? false,
      host,
      port,
      version: result.version ?? '',
      protocol: result.protocol ?? 0,
      playersOnline: result.playersOnline ?? 0,
      playersMax: result.playersMax ?? 0,
      playerList: result.playerList ?? [],
      motd: result.description ?? '',
      pingMs: result.latencyMs ?? -1,
      lastChecked: Date.now(),
    }
  } catch {
    return {
      online: false,
      host,
      port,
      version: '',
      protocol: 0,
      playersOnline: 0,
      playersMax: 0,
      playerList: [],
      motd: '',
      pingMs: -1,
      lastChecked: Date.now(),
    }
  }
}

export function classifyModSide(modFileName: string): 'client' | 'server' | 'both' {
  const clientOnlyPatterns = [
    /optifine/i, /sodium/i, /lithium/i, /iris/i, /phosphor/i,
    /betterfps/i, /fpsplus/i, /chunkanimator/i,
    /customcrosshair/i, /damageindicator/i, /minimap/i,
    /journeymap/i, /xaero/i, /voxelmap/i, /mapwriter/i,
    /neat/i, /waila/i, /hwyla/i, /jade/i, /theoneprobe/i,
    /appleskin/i, /jei/i, /rei/i, /emi/i,
    /inventoryhud/i, /itemscroller/i, /mousewheelie/i,
    /shulkerboxtooltip/i, /inventario/i,
    /soundfilters/i, /presencefootsteps/i, /dynamic surroundings/i,
    /visualworkbench/i, /concretepowdertoblock/i,
    /waila/i, /hwyla/i, /jade/i,
  ]
  const serverOnlyPatterns = [
    /worldguard/i, /worldedit/i, /essentials/i, /luckperms/i,
    /vault/i, /economy/i, /permissions/i, /coreprotect/i,
    /logblock/i, /griefprevention/i, /towny/i,
  ]

  for (const p of clientOnlyPatterns) {
    if (p.test(modFileName)) return 'client'
  }
  for (const p of serverOnlyPatterns) {
    if (p.test(modFileName)) return 'server'
  }
  return 'both'
}

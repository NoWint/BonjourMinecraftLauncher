import { minecraftAPI } from '../../api/tauri-bridge'

export function createServerEntry(name: string, address: string, port: number = 25565): ServerEntry {
  return {
    id: `srv-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`,
    name,
    address,
    port,
    tags: [],
    addedAt: Date.now(),
    playCount: 0,
    isFavorite: false,
  }
}

export function parseServerAddress(input: string): { host: string; port: number } {
  const trimmed = input.trim()
  if (trimmed.includes(':')) {
    const parts = trimmed.split(':')
    return { host: parts[0], port: parseInt(parts[1]) || 25565 }
  }
  return { host: trimmed, port: 25565 }
}

export function formatServerAddress(host: string, port: number): string {
  return port === 25565 ? host : `${host}:${port}`
}

export function sortServers(servers: ServerEntry[], sortBy: 'name' | 'lastPlayed' | 'playCount' | 'ping' = 'name'): ServerEntry[] {
  const sorted = [...servers]
  switch (sortBy) {
    case 'name':
      sorted.sort((a, b) => a.name.localeCompare(b.name))
      break
    case 'lastPlayed':
      sorted.sort((a, b) => (b.lastPlayedAt || 0) - (a.lastPlayedAt || 0))
      break
    case 'playCount':
      sorted.sort((a, b) => b.playCount - a.playCount)
      break
  }
  const favorites = sorted.filter(s => s.isFavorite)
  const others = sorted.filter(s => !s.isFavorite)
  return [...favorites, ...others]
}

export function filterServersByGroup(servers: ServerEntry[], groupId: string | undefined, groups: ServerGroup[]): ServerEntry[] {
  if (!groupId || groupId === 'all') return servers
  return servers.filter(s => s.groupId === groupId)
}

export function filterServersByTag(servers: ServerEntry[], tag: string): ServerEntry[] {
  return servers.filter(s => s.tags.includes(tag))
}

export function searchServers(servers: ServerEntry[], query: string): ServerEntry[] {
  const q = query.toLowerCase()
  return servers.filter(s =>
    s.name.toLowerCase().includes(q) ||
    s.address.toLowerCase().includes(q) ||
    s.tags.some(t => t.toLowerCase().includes(q))
  )
}

